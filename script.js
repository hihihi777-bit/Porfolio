let currentLang = localStorage.getItem("nva-lang") || "vi";

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("nva-lang", lang);
  document.documentElement.lang = lang;

  const dict = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  // Button shows the OTHER language (what you switch TO)
  const langLabel = document.getElementById("langLabel");
  if (langLabel) langLabel.textContent = lang === "vi" ? "EN" : "VI";
}

// ========== Theme toggle ==========
const themeToggle = document.getElementById("themeToggle");
const root = document.documentElement;
const themeIcon = themeToggle.querySelector("i");

function applyTheme(theme) {
  root.setAttribute("data-theme", theme);
  themeIcon.className = theme === "dark" ? "fa-solid fa-moon" : "fa-solid fa-sun";
  localStorage.setItem("nva-theme", theme);
}

// Mặc định dark
applyTheme(localStorage.getItem("nva-theme") || "light");

themeToggle.addEventListener("click", () => {
  const next = root.getAttribute("data-theme") === "dark" ? "light" : "dark";
  applyTheme(next);
});

// ========== Language toggle ==========
const langToggle = document.getElementById("langToggle");
langToggle.addEventListener("click", () => {
  const next = currentLang === "vi" ? "en" : "vi";
  applyLanguage(next);
});

// Apply saved language on load
applyLanguage(currentLang);

// ========== Mobile menu ==========
const hamburger = document.getElementById("hamburger");
const navLinks = document.getElementById("navLinks");
const hamburgerIcon = hamburger.querySelector("i");

hamburger.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  hamburgerIcon.className = isOpen ? "fa-solid fa-xmark" : "fa-solid fa-bars";
});

navLinks.querySelectorAll("a").forEach((a) =>
  a.addEventListener("click", () => {
    navLinks.classList.remove("open");
    hamburgerIcon.className = "fa-solid fa-bars";
  })
);

// ========== Nav scroll + to-top ==========
const nav = document.getElementById("nav");
const toTop = document.getElementById("toTop");

window.addEventListener(
  "scroll",
  () => {
    nav.classList.toggle("scrolled", window.scrollY > 40);
    toTop.classList.toggle("show", window.scrollY > 500);
    highlightNav();
  },
  { passive: true }
);

toTop.addEventListener("click", () =>
  window.scrollTo({ top: 0, behavior: "smooth" })
);

// ========== Highlight nav ==========
const sections = [...document.querySelectorAll("section[id]")];
const links = [...document.querySelectorAll(".nav-link")];

function highlightNav() {
  const pos = window.scrollY + 100;
  let current = sections[0]?.id;
  sections.forEach((s) => {
    if (pos >= s.offsetTop) current = s.id;
  });
  links.forEach((l) =>
    l.classList.toggle("active", l.getAttribute("href") === `#${current}`)
  );
}

// ========== Typing effect ==========
const roles = [
  "Web Developer",
  "PHP Developer",
  "WordPress Developer",
  "Laravel Developer",
];
const typedEl = document.getElementById("typed");
let roleIdx = 0;
let charIdx = 0;
let deleting = false;

function typeLoop() {
  const word = roles[roleIdx];
  charIdx += deleting ? -1 : 1;
  typedEl.textContent = word.slice(0, charIdx);

  let delay = deleting ? 42 : 88;
  if (!deleting && charIdx === word.length) {
    delay = 1600;
    deleting = true;
  } else if (deleting && charIdx === 0) {
    deleting = false;
    roleIdx = (roleIdx + 1) % roles.length;
    delay = 320;
  }
  setTimeout(typeLoop, delay);
}
typeLoop();

// ========== Reveal on scroll ==========
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    });
  },
  { threshold: 0.1 }
);

document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));

